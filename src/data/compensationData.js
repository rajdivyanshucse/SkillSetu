// Helper to get skill association by ID or name
export const getSkillAssociation = (identifier) => {
  const norm = identifier.toLowerCase();
  return (
    skillCompensationAssociations.find(
      (s) => s.id.toLowerCase() === norm || s.name.toLowerCase() === norm
    ) || null
  );
};
